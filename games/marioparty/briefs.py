def E(centre, radii, **kw):
    return {"e": [centre[0], centre[1], radii[0], radii[1]], **kw}


def L(pts, w, c=K):
    return {"line": pts, "w": w, "c": c}


def P(pts, c):
    return {"poly": pts, "c": c}


def R(x0, y0, x1, y1, c):
    return {"rect": [x0, y0, x1, y1], "c": c}


def eye(c, r, iris, look=(0, 0), irisr=0.6, pupil=0.55, ring=None, border=0.0, rot=0, irisy=1.0, sclera=W):
    e = {"c": list(c), "r": list(r), "iris": iris, "look": list(look), "irisr": irisr, "pupil": pupil, "rot": rot,
         "irisy": irisy, "sclera": sclera}
    if ring:
        e["ring"] = ring
    if border:
        e["border"] = border
    return {"eye": e}


def brief(base, *ops, **kw):
    return {"base": base, "ops": list(ops), **kw}


